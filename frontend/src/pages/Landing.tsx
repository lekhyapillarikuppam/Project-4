import { Link } from "react-router-dom";
import { useAuth } from "../auth/AuthContext";
import { CheckList } from "../components/VariantCard";
import { Price } from "../components/ui";
import { inr } from "../lib/format";
import { useDocumentTitle } from "../lib/title";
import example from "./landing-example.json";

const STEPS = [
  { title: "Tell us the trip", text: "Where, when, how many people, your budget and what you enjoy." },
  { title: "Compare 2–3 plans", text: "Saver, Balanced and Experience — each checked against the budget, opening hours and travel times." },
  { title: "Refine and keep", text: "Pick a plan, see every day on a map, change it in chat, and save it to My Trips." },
];

// Day 2 of a real engine plan (DEL→JAI, 2 people), generated by eval/make_landing_example.py from the curated data;
// backend/tests/test_landing_example.py fails if it drifts from what the engine produces.
type Row = { leg: string; cost: number } | { lunch: string } | { time: string; name: string; fee: number };
const EXAMPLE = example as { title: string; people: number; rows: Row[] };

function ExampleDay() {
  let n = 0;
  return (
    <figure className="card shadow-md" aria-labelledby="example-day">
      <figcaption id="example-day" className="flex flex-wrap items-baseline justify-between gap-2">
        <span className="font-display text-lg font-semibold tracking-tight">{EXAMPLE.title}</span>
        <span className="text-xs font-medium text-ink-500">From a real plan, {EXAMPLE.people} people</span>
      </figcaption>
      <ol className="mt-3 space-y-1 text-sm">
        {EXAMPLE.rows.map((r, i) => {
          if ("leg" in r) return (
            <li key={i} className="ml-[5.75rem] border-l-2 border-dashed border-sand-300 py-1 pl-3 text-[13px] text-ink-500">
              {r.leg} · <Price className="num">{inr(r.cost)}</Price>
            </li>
          );
          if ("lunch" in r) return (
            <li key={i} className="ml-[5.75rem] py-1">
              <span className="num rounded bg-sand-100 px-2 py-0.5 text-xs font-medium text-ink-700">{r.lunch}</span>
            </li>
          );
          n += 1;
          return (
            <li key={i} className="grid grid-cols-[5rem,1fr] gap-x-3 py-0.5">
              <span className="num pt-px text-ink-700">{r.time}</span>
              <span><span className="text-[15px] font-semibold">{n}. {r.name}</span>{" "}
                <span className="text-ink-500">{r.fee ? <Price className="num">{inr(r.fee)}</Price> : "free entry"}</span></span>
            </li>
          );
        })}
      </ol>
      <CheckList className="mt-4 border-t border-sand-200 pt-3" />
    </figure>
  );
}

export default function Landing() {
  const { user } = useAuth();
  useDocumentTitle(null);
  return (
    <div className="space-y-12">
      <section className="grid items-center gap-8 pt-2 lg:grid-cols-[1.1fr,1fr] lg:gap-12 lg:pt-6">
        <div>
          <h1 className="max-w-xl text-4xl font-bold leading-[1.05] sm:text-5xl">Budget trips that actually work.</h1>
          <p className="mt-4 max-w-xl text-lg text-ink-700">
            Tripwise plans a complete trip between 15 Indian cities — transport, hotel, a day-by-day itinerary and every rupee —
            and every plan fits your budget, opening hours and travel times.
          </p>
          <div className="mt-6 flex flex-wrap gap-3">
            <Link to={user ? "/new" : "/signup"} className="btn-primary px-6 py-3 text-base">Plan a trip</Link>
          </div>
          <p className="mt-4 text-sm text-ink-500">Prices are estimates compiled for planning; Tripwise does not book anything.</p>
        </div>
        <ExampleDay />
      </section>
      <section aria-labelledby="how" className="border-t border-sand-200 pt-8">
        <h2 id="how" className="mb-4 text-xl font-semibold">How it works</h2>
        <ol className="grid gap-6 sm:grid-cols-3">
          {STEPS.map((s, i) => (
            <li key={s.title} className="flex gap-3">
              <span aria-hidden className="num flex h-7 w-7 shrink-0 items-center justify-center rounded-full bg-accent-700 text-sm font-semibold text-white">
                {i + 1}
              </span>
              <div>
                <h3 className="font-semibold">{s.title}</h3>
                <p className="mt-1 text-sm text-ink-700">{s.text}</p>
              </div>
            </li>
          ))}
        </ol>
      </section>
    </div>
  );
}
